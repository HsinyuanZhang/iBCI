"""Stage0 markdown writers. Facts that are not uniquely determined stay UNRESOLVED."""
from __future__ import annotations

from typing import Any, Mapping


def _status(payload: Mapping[str, Any] | None, default: str = "NOT_RUN") -> str:
    if not payload:
        return default
    return str(payload.get("status", default))


