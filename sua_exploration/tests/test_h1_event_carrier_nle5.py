def test_nle5_source_nonlinear_map_is_deterministic_and_tag_shuffle_changes_phi() -> None:
    events=[]
    for i in range(32):
        events.append(v1.MovementEvent(i,v1.MOVEMENT_TAGS[i % len(v1.MOVEMENT_TAGS)],float(i),i, float(i),float(i)+.2+.01*(i%3),.2+.01*(i%3),5,
            np.asarray([np.sin(i+j) for j in range(7)]),np.full(176,.01*i)))
    names=nle5.source_names_for_outer("19250101")
    sessions={name:SimpleNamespace(events=tuple(events)) for name in names}
    first=nle5.fit_nonlinear_map(sessions,outer_date="19250101"); second=nle5.fit_nonlinear_map(sessions,outer_date="19250101")
    np.testing.assert_array_equal(first.transform(events),second.transform(events))
    shuffled=[e.tag for e in events[::-1]]
    assert not np.array_equal(first.transform(events),first.transform(events,shuffled))
    # A target response generated by the nonlinear source phi is recovered by the same 5-D path.
    z=first.transform(events); response=np.zeros((len(z),176)); response[:,:2]=z@np.array([[.2,-.1],[.1,.3],[.4,.2],[-.2,.1]])
    carrier,_=nle5.fit_carrier(z,response)
    recovered=np.mean((nle5.predict(carrier,z)[:,:2]-response[:,:2])**2)
    intercept=np.mean((response[:,:2]-response[:,:2].mean(0))**2)
    assert recovered < intercept


